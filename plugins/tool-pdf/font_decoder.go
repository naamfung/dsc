// Package main — tool-pdf 插件的字体编码解码层。
//
// PDF 文本字符串字节需要经字体编码解码为 Unicode：
//
//   - Type1/TrueType 单字节字体：用 Encoding 字典或默认 WinAnsiEncoding / MacRomanEncoding
//   - Type0（CJK）多字节字体：用 CMap（如 UniGB-UTF16-H）把字符代码映射到 CID → GID
//     最可靠路径是 ToUnicode CMap，直接把字符代码（1-2 字节）映射到 Unicode 字符串
//
// 本层实现：
//
//  1. WinAnsi / MacRoman / StandardEncoding 三套基础编码表（PDF 标准 14 字体的默认编码）
//  2. ToUnicode CMap 解析（bfchar / bfrange 两类条目）
//  3. 简单 Encoding 字典差异（Differences 数组）的有限支持
//
// 设计原则：尽力而为解码。无法识别的字节回退为 '?' 并记数，保证不返回错误。
// 字体识别失败的 PDF 仍能给出粗略文本，便于模型判断是否值得继续。
package main

import (
	"bufio"
	"bytes"
	"encoding/hex"
	"fmt"
	"strconv"
	"strings"
)

// fontDecoder 把字符代码字节解码为 Unicode 字符串。
// 同一字符代码经不同字体有不同含义，故解码器绑定具体字体实例。
type fontDecoder struct {
	// 优先级：ToUnicode CMap > Differences > 基础编码 > 默认
	toUnicode   map[string]string // 字符代码（大端 hex） → Unicode 字符串
	differences map[byte]string   // 单字节字符代码 → Unicode 字符串（仅 Type1/TrueType）
	base        string            // 基础编码名：winansi / macroman / standard / identity-h / identity-v
	isCID       bool              // 是否为 CID 字体（2 字节字符代码）
}

// newFontDecoder 创建一个空解码器，调用方按可用信息填充字段。
func newFontDecoder() *fontDecoder {
	return &fontDecoder{
		toUnicode:   map[string]string{},
		differences: map[byte]string{},
		base:        "winansi",
		isCID:       false,
	}
}

// decode 把 PDF 内容流中的字符串字节解码为 Unicode 字符串。
// CID 字体按 2 字节大端解码；单字节字体按基础编码 + Differences 解码。
// 不可识别的字节回退为 '?'。
func (d *fontDecoder) decode(bb []byte) string {
	if len(bb) == 0 {
		return ""
	}
	var b strings.Builder
	if d.isCID {
		for i := 0; i+1 < len(bb); i += 2 {
			code := fmt.Sprintf("%04X", uint16(bb[i])<<8|uint16(bb[i+1]))
			if s, ok := d.toUnicode[code]; ok {
				b.WriteString(s)
				continue
			}
			// 部分 CIDFont 用 1 字节代码（Identity-H 中混合 1/2 字节的情况罕见）
			if bb[i] != 0 && bb[i+1] == 0 {
				code1 := fmt.Sprintf("%02X", bb[i])
				if s, ok := d.toUnicode[code1]; ok {
					b.WriteString(s)
					continue
				}
			}
			b.WriteByte('?')
		}
		// 奇数字节末尾忽略
		return b.String()
	}
	// 单字节字体
	for _, c := range bb {
		// 优先 ToUnicode（部分 Type1 字体也提供 ToUnicode）
		code := fmt.Sprintf("%02X", c)
		if s, ok := d.toUnicode[code]; ok {
			b.WriteString(s)
			continue
		}
		// Differences 覆盖
		if s, ok := d.differences[c]; ok {
			b.WriteString(s)
			continue
		}
		// 基础编码
		switch d.base {
		case "winansi":
			if r, ok := winAnsiTable[c]; ok {
				b.WriteRune(r)
			} else if c < 0x80 {
				b.WriteByte(c)
			} else {
				b.WriteByte('?')
			}
		case "macroman":
			if r, ok := macRomanTable[c]; ok {
				b.WriteRune(r)
			} else if c < 0x80 {
				b.WriteByte(c)
			} else {
				b.WriteByte('?')
			}
		case "standard":
			if r, ok := standardEncodingTable[c]; ok {
				b.WriteRune(r)
			} else if c < 0x80 {
				b.WriteByte(c)
			} else {
				b.WriteByte('?')
			}
		default:
			// 未知编码：尽力 ASCII
			if c < 0x80 {
				b.WriteByte(c)
			} else {
				b.WriteByte('?')
			}
		}
	}
	return b.String()
}

// parseToUnicodeCMap 解析 PDF ToUnicode CMap 文本流，填充 d.toUnicode。
// CMap 文法（PDF 9.10.3）：
//
//	1 beginbfchar
//	<0041> <0041>
//	endbfchar
//	2 beginbfrange
//	<0000> <005A> <0041>
//	<0061> <007A> [<0061> <0062> ... <007A>]
//	endbfrange
//
// bfchar：单字符代码 → 单 Unicode 字符（或字符串）
// bfrange：连续字符代码区间 → Unicode 起始字符 或 字符串数组
func (d *fontDecoder) parseToUnicodeCMap(raw []byte) {
	scanner := bufio.NewScanner(bytes.NewReader(raw))
	scanner.Buffer(make([]byte, 64*1024), 4*1024*1024) // CMap 可能很大
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "%") {
			continue
		}
		// bfchar 段
		if strings.HasSuffix(line, "beginbfchar") {
			count := parseBfHeader(line)
			for i := 0; i < count && scanner.Scan(); i++ {
				parts := strings.Fields(scanner.Text())
				if len(parts) >= 2 {
					src := strings.Trim(parts[0], "<>")
					dst := strings.Trim(parts[1], "<>")
					d.toUnicode[src] = decodeUnicodeHex(dst)
				}
			}
			continue
		}
		// bfrange 段
		if strings.HasSuffix(line, "beginbfrange") {
			count := parseBfHeader(line)
			for i := 0; i < count && scanner.Scan(); i++ {
				parts := strings.Fields(scanner.Text())
				if len(parts) < 3 {
					continue
				}
				srcLo := strings.Trim(parts[0], "<>")
				srcHi := strings.Trim(parts[1], "<>")
				dst := parts[2]
				applyBfRange(d.toUnicode, srcLo, srcHi, dst)
			}
			continue
		}
	}
}

// parseBfHeader 解析 "3 beginbfchar" 中的计数。
func parseBfHeader(line string) int {
	parts := strings.Fields(line)
	if len(parts) < 2 {
		return 0
	}
	n, _ := strconv.Atoi(parts[0])
	if n < 0 || n > 1<<20 {
		return 0
	}
	return n
}

// applyBfRange 把一个 bfrange 条目展开为 toUnicode 表项。
// dst 形式：<XXXX>（单一目标）或 [<a> <b> <c> ...]（数组目标）。
func applyBfRange(table map[string]string, srcLo, srcHi, dst string) {
	lo, err1 := strconv.ParseUint(srcLo, 16, 32)
	hi, err2 := strconv.ParseUint(srcHi, 16, 32)
	if err1 != nil || err2 != nil || hi < lo || hi-lo > 65535 {
		return
	}
	if strings.HasPrefix(dst, "[") {
		// 数组形式：每个元素是一个 <XXXX> Unicode 字符串
		fields := strings.Fields(strings.Trim(dst, "[]"))
		for i := uint64(0); i <= hi-lo && i < uint64(len(fields)); i++ {
			code := fmt.Sprintf("%04X", lo+i)
			// 源代码可能为 1 或 2 字节，宽度按 srcLo 长度补齐
			if len(srcLo) == 2 {
				code = fmt.Sprintf("%02X", lo+i)
			}
			table[code] = decodeUnicodeHex(strings.Trim(fields[i], "<>"))
		}
		return
	}
	// 单一目标：<XXXX>；起始 Unicode 字符 + 偏移
	dstClean := strings.Trim(dst, "<>")
	dstBytes, err := hex.DecodeString(dstClean)
	if err != nil {
		return
	}
	// dst 通常是 UTF-16BE 字符序列
	dstStr := decodeUTF16BE(dstBytes)
	if len(dstStr) == 0 {
		return
	}
	baseRune := []rune(dstStr)[0]
	for i := uint64(0); i <= hi-lo; i++ {
		code := fmt.Sprintf("%04X", lo+i)
		if len(srcLo) == 2 {
			code = fmt.Sprintf("%02X", lo+i)
		}
		table[code] = string([]rune{baseRune + rune(i)})
	}
}

// decodeUnicodeHex 把 ToUnicode CMap 中的 <XXXX> 目标解码为字符串。
// 目标用 UTF-16BE 编码（每 4 hex 位为一个 16 位码元），代理对正确处理。
func decodeUnicodeHex(hexStr string) string {
	bb, err := hex.DecodeString(hexStr)
	if err != nil {
		return ""
	}
	return decodeUTF16BE(bb)
}

// decodeUTF16BE 把 UTF-16BE 字节切片解码为 Go string。
// 代理对正确合并；孤立代理保留为 U+FFFD。
func decodeUTF16BE(bb []byte) string {
	if len(bb)%2 != 0 {
		if len(bb) > 0 {
			bb = append(bb, 0)
		} else {
			return ""
		}
	}
	var b strings.Builder
	for i := 0; i+1 < len(bb); i += 2 {
		code := uint16(bb[i])<<8 | uint16(bb[i+1])
		if code >= 0xD800 && code <= 0xDBFF && i+3 < len(bb) {
			lo := uint16(bb[i+2])<<8 | uint16(bb[i+3])
			if lo >= 0xDC00 && lo <= 0xDFFF {
				r := 0x10000 + (uint32(code-0xD800) << 10) + uint32(lo-0xDC00)
				b.WriteRune(rune(r))
				i += 2
				continue
			}
		}
		b.WriteRune(rune(code))
	}
	return b.String()
}

